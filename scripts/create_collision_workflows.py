#!/usr/bin/env python3
"""Publish the two deterministic collision workflows to the local manager."""
from __future__ import annotations

import json
import urllib.request
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
BASE_URL = "http://127.0.0.1:8890/api/v1"
LIBRARY_DIR = ROOT / "output/scenarios/citynde/library"
OUTPUT = ROOT / "output/validation/collision_scenarios_20260828/workflows.json"

SCENARIOS = (
    (
        "xa_wenying_scripted_cutin_collision",
        "事故验证-车辆切入并碰撞主车-Transfer1-12秒",
        "collision_av_cutin_transfer1_12s",
    ),
    (
        "xa_wenying_scripted_rearend_collision",
        "事故验证-主车追尾急停前车-Transfer1-12秒",
        "collision_av_rearend_transfer1_12s",
    ),
)


def _request(path: str, payload: dict[str, Any] | None = None) -> dict[str, Any]:
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    data = None if payload is None else json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        BASE_URL + path,
        data=data,
        headers={"Content-Type": "application/json"} if data is not None else {},
        method="POST" if data is not None else "GET",
    )
    with opener.open(request, timeout=30) as response:
        result = json.loads(response.read().decode("utf-8"))
    if not result.get("ok", False):
        raise RuntimeError(str(result.get("error") or result))
    return result


