def main() -> int:
    existing = _request("/workflows").get("workflows") or []
    by_name = {str(item.get("name") or ""): item for item in existing}
    by_scenario = {
        str(item.get("scenario_id") or ""): item
        for item in existing
        if str(item.get("scenario_id") or "").startswith("xa-wenying-scripted-")
    }
    records = []
    for stem, name, recording_name in SCENARIOS:
        metadata_path = LIBRARY_DIR / f"{stem}.pkl.meta.json"
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        workflow = _workflow(metadata, name)
        current = by_name.get(name) or by_scenario.get(str(metadata["library_id"]))
        if current:
            workflow["id"] = current["id"]
            workflow["created_at"] = current.get("created_at")
        result = _request("/workflows/action", {"type": "save", "workflow": workflow})
        saved = dict(result["workflow"])
        records.append(
            {
                "id": saved["id"],
                "name": saved["name"],
                "scenario_id": saved["scenario_id"],
                "duration_seconds": saved["duration_seconds"],
                "recording_name": recording_name,
                "expected_collision": metadata["expected_collision"],
            }
        )
    manifest = {
        "schema": "trafficwm.collision-workflows.v2",
        "count": len(records),
        "workflows": records,
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps({**manifest, "path": str(OUTPUT)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
